CREATE TABLE `billing_cycles` (
  `cycle_id` int unsigned NOT NULL AUTO_INCREMENT,
  `boarding_id` int unsigned NOT NULL,
  `period_start` date NOT NULL,
  `cycle_number` int unsigned NOT NULL DEFAULT '1',
  `replaces_cycle_id` int unsigned DEFAULT NULL,
  `due_date` date NOT NULL,
  `electricity_total` decimal(14,2) DEFAULT NULL,
  `water_total` decimal(14,2) DEFAULT NULL,
  `electricity_unallocated` decimal(14,2) NOT NULL DEFAULT '0.00',
  `water_unallocated` decimal(14,2) NOT NULL DEFAULT '0.00',
  `state` enum('draft','locked','void') NOT NULL DEFAULT 'draft',
  `version` int unsigned NOT NULL DEFAULT '0',
  `source_digest` char(64) DEFAULT NULL,
  `locked_at` datetime(6) DEFAULT NULL COMMENT 'UTC',
  `created_by` int unsigned NOT NULL,
  `created_at` datetime(6) NOT NULL COMMENT 'UTC',
  `active_period` date GENERATED ALWAYS AS ((case when (`state` <> _utf8mb4'void') then `period_start` else NULL end)) STORED,
  `utility_source` enum('manual_legacy','expenses') NOT NULL DEFAULT 'manual_legacy',
  `utility_expense_digest` char(64) DEFAULT NULL,
  `utility_snapshot` json DEFAULT NULL,
  PRIMARY KEY (`cycle_id`),
  UNIQUE KEY `uq_billing_cycle_number` (`boarding_id`,`period_start`,`cycle_number`),
  UNIQUE KEY `uq_billing_cycle_identity` (`cycle_id`,`boarding_id`,`period_start`),
  UNIQUE KEY `uq_billing_cycle_active` (`boarding_id`,`active_period`),
  KEY `idx_billing_cycle_replacement` (`replaces_cycle_id`),
  KEY `fk_billing_cycle_creator` (`created_by`),
  CONSTRAINT `fk_billing_cycle_boarding` FOREIGN KEY (`boarding_id`) REFERENCES `boardings` (`boarding_id`),
  CONSTRAINT `fk_billing_cycle_creator` FOREIGN KEY (`created_by`) REFERENCES `users` (`user_id`),
  CONSTRAINT `fk_billing_cycle_replacement` FOREIGN KEY (`replaces_cycle_id`) REFERENCES `billing_cycles` (`cycle_id`),
  CONSTRAINT `chk_billing_cycle_lock` CHECK (((`state` = _utf8mb4'draft') or ((`source_digest` is not null) and (`locked_at` is not null) and (`electricity_total` is not null) and (`water_total` is not null)))),
  CONSTRAINT `chk_billing_cycle_period` CHECK (((dayofmonth(`period_start`) = 1) and (`due_date` >= `period_start`))),
  CONSTRAINT `chk_billing_cycle_unallocated` CHECK (((`electricity_unallocated` >= 0) and (`water_unallocated` >= 0))),
  CONSTRAINT `chk_billing_cycle_utilities` CHECK ((((`electricity_total` is null) and (`water_total` is null)) or ((`electricity_total` >= 0) and (`water_total` >= 0) and (`electricity_total` is not null) and (`water_total` is not null))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `expenses` (
  `expense_id` int unsigned NOT NULL AUTO_INCREMENT,
  `boarding_id` int unsigned NOT NULL,
  `expense_name` varchar(150) NOT NULL,
  `amount` decimal(14,2) NOT NULL,
  `expense_date` date NOT NULL,
  `accounting_period` date DEFAULT NULL COMMENT 'First day of the selected accounting month; NULL uses the paid date month',
  `request_key` char(32) NOT NULL,
  `revision` int unsigned NOT NULL DEFAULT '0',
  `created_by` int unsigned NOT NULL,
  `created_at` datetime(6) NOT NULL COMMENT 'UTC',
  `updated_at` datetime(6) NOT NULL COMMENT 'UTC',
  `archived_by` int unsigned DEFAULT NULL,
  `archived_at` datetime(6) DEFAULT NULL COMMENT 'UTC',
  `category` enum('electricity','water','other') NOT NULL DEFAULT 'other',
  `utility_period` date DEFAULT NULL,
  `notes` varchar(500) DEFAULT NULL,
  `charge_to_tenants` tinyint(1) NOT NULL DEFAULT '0',
  PRIMARY KEY (`expense_id`),
  UNIQUE KEY `uq_expense_request` (`boarding_id`,`request_key`),
  KEY `idx_expense_month` (`boarding_id`,`archived_at`,`expense_date`,`expense_id`),
  KEY `idx_expense_accounting_period` (`boarding_id`,`archived_at`,`accounting_period`),
  KEY `fk_expense_creator` (`created_by`),
  KEY `fk_expense_archiver` (`archived_by`),
  KEY `idx_expense_utility` (`boarding_id`,`utility_period`,`category`,`archived_at`),
  CONSTRAINT `fk_expense_archiver` FOREIGN KEY (`archived_by`) REFERENCES `users` (`user_id`),
  CONSTRAINT `fk_expense_boarding` FOREIGN KEY (`boarding_id`) REFERENCES `boardings` (`boarding_id`),
  CONSTRAINT `fk_expense_creator` FOREIGN KEY (`created_by`) REFERENCES `users` (`user_id`),
  CONSTRAINT `chk_expense_amount` CHECK (((`amount` >= 0) and ((`category` <> _utf8mb4'other') or (`amount` > 0)))),
  CONSTRAINT `chk_expense_archive` CHECK ((((`archived_at` is null) and (`archived_by` is null)) or ((`archived_at` is not null) and (`archived_by` is not null)))),
  CONSTRAINT `chk_expense_accounting_period` CHECK (`accounting_period` IS NULL OR (`accounting_period` BETWEEN '2000-01-01' AND '2100-12-01' AND DAYOFMONTH(`accounting_period`)=1)),
  CONSTRAINT `chk_expense_name` CHECK ((char_length(trim(`expense_name`)) > 0)),
  CONSTRAINT `chk_expense_sharing_flag` CHECK ((`charge_to_tenants` in (0,1))),
  CONSTRAINT `chk_expense_utility_period` CHECK ((((`category` = _utf8mb4'other') and (`charge_to_tenants` = false) and (`utility_period` is null)) or ((`category` = _utf8mb4'other') and (`charge_to_tenants` = true) and (`utility_period` is not null) and (dayofmonth(`utility_period`) = 1)) or ((`category` in (_utf8mb4'electricity',_utf8mb4'water')) and (`charge_to_tenants` = false) and (`utility_period` is not null) and (dayofmonth(`utility_period`) = 1))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

