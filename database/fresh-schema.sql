  CONSTRAINT `chk_restricted_scope` CHECK ((((`session_scope` = _utf8mb4'normal') and (`suspension_event_id` is null)) or ((`session_scope` = _utf8mb4'restricted') and (`suspension_event_id` is not null) and (`remember_me` = 0) and (`expires_at` <= (`created_at` + interval 15 minute)))))
